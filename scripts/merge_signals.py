#!/usr/bin/env python3
"""Parse signal tables from research/tracks/*.md (and landscape LAND- rows) into one dataset.

Usage:
  python3 scripts/merge_signals.py --list                 # compact list: ID | strength | who | pain (for theming)
  python3 scripts/merge_signals.py --stats                # counts per track and strength
  python3 scripts/merge_signals.py --build                # write research/SIGNALS.md using scripts/signal_themes.py
  python3 scripts/merge_signals.py --csv out.csv          # dump all rows

Theme assignment and duplicate merges live in scripts/signal_themes.py:
  THEMES = [("theme-key", "Theme title", "one-line description"), ...]
  ASSIGN = {"HN-01": "theme-key", ...}
  MERGES = {"RED-13": "HN-02", ...}   # duplicate -> canonical (same pain AND same person/thread, or same pain restated)
"""
import argparse
import csv
import glob
import importlib.util
import os
import re
import sys
from collections import Counter, defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TRACK_GLOB = os.path.join(ROOT, "research", "tracks", "*.md")
EXTRA = [os.path.join(ROOT, "research", "landscape", "launches.md")]
ID_RE = re.compile(r"^[A-Z][A-Z0-9]{1,6}-\d{1,3}$")


def parse_file(path):
    rows = []
    track = os.path.basename(path).replace(".md", "")
    with open(path, encoding="utf-8") as f:
        for line in f:
            if not line.startswith("|"):
                continue
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if len(cells) < 7 or not ID_RE.match(cells[0]):
                continue
            # tolerate extra columns: take first 7 in brief order
            rid, who, pain, quote, url, date, strength = cells[:7]
            rows.append({
                "id": rid, "who": who, "pain": pain, "quote": quote, "url": url,
                "date": date, "strength": strength.lower().strip("* "), "track": track,
            })
    return rows


def load_all():
    rows = []
    for p in sorted(glob.glob(TRACK_GLOB)) + EXTRA:
        if os.path.exists(p):
            rows += parse_file(p)
    return rows


def load_themes():
    p = os.path.join(ROOT, "scripts", "signal_themes.py")
    spec = importlib.util.spec_from_file_location("signal_themes", p)
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m.THEMES, m.ASSIGN, getattr(m, "MERGES", {})


def esc(s):
    return str(s).replace("|", "/").strip()


def build(rows):
    themes, assign, merges = load_themes()
    by_id = {r["id"]: r for r in rows}
    dupes = defaultdict(list)
    for d, canon in merges.items():
        if d in by_id and canon in by_id:
            dupes[canon].append(d)
    grouped = defaultdict(list)
    unassigned = []
    for r in rows:
        if r["id"] in merges:
            continue
        t = assign.get(r["id"])
        if not t:
            unassigned.append(r["id"])
            t = "other"
        grouped[t].append(r)
    order = {"strong": 0, "medium": 1, "weak": 2}
    distinct = sum(len(v) for v in grouped.values())
    strong = sum(1 for v in grouped.values() for r in v if r["strength"].startswith("strong"))
    tracks = Counter(r["track"] for r in rows)
    out = [
        "# Signals",
        "",
        "Consolidated pain and demand signals from the research tracks in `research/tracks/` (plus LAND- rows from "
        "`research/landscape/launches.md`). Generated by `scripts/merge_signals.py --build` from the track files and the "
        "theme map in `scripts/signal_themes.py`. Each row keeps its original track ID so idea files can cite it.",
        "",
        f"**Counts:** {len(rows)} raw rows, {len(merges)} merged as duplicates, **{distinct} distinct signals** "
        f"({strong} strong). Themes: {len([t for t in themes if grouped.get(t[0])])}.",
        "",
        "Raw rows per track: " + ", ".join(f"{k} {v}" for k, v in sorted(tracks.items())) + ".",
        "",
        "Format: `| ID | Who has the pain | The pain in one line | \"Exact quote\" | URL | Date | Strength |`. "
        "Duplicates merged into a row are listed in the ID cell as `(+ID)`; their full rows stay in the track files.",
        "",
        "## Theme overview",
        "",
        "| Theme | Signals | Strong | What it is about |",
        "|---|---|---|---|",
    ]
    theme_list = list(themes) + [("other", "Other / uncategorized", "Signals not yet assigned to a theme")]
    for key, title, desc in theme_list:
        g = grouped.get(key, [])
        if not g:
            continue
        s = sum(1 for r in g if r["strength"].startswith("strong"))
        out.append(f"| [{title}](#{re.sub(r'[^a-z0-9 -]', '', title.lower()).replace(' ', '-')}) | {len(g)} | {s} | {desc} |")
    for key, title, desc in theme_list:
        g = grouped.get(key, [])
        if not g:
            continue
        g.sort(key=lambda r: (order.get(r["strength"].split()[0] if r["strength"] else "weak", 3), r["id"]))
        out += ["", f"## {title}", "", desc, "",
                "| ID | Who has the pain | The pain in one line | \"Exact quote\" | URL | Date | Strength |",
                "|---|---|---|---|---|---|---|"]
        for r in g:
            idcell = r["id"] + (" (+" + ", +".join(sorted(dupes[r["id"]])) + ")" if dupes.get(r["id"]) else "")
            out.append(f"| {idcell} | {esc(r['who'])} | {esc(r['pain'])} | {esc(r['quote'])} | {esc(r['url'])} | {esc(r['date'])} | {esc(r['strength'])} |")
    with open(os.path.join(ROOT, "research", "SIGNALS.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print(f"SIGNALS.md written: {distinct} distinct ({strong} strong), {len(merges)} merged, {len(unassigned)} unassigned")
    if unassigned:
        print("UNASSIGNED:", " ".join(unassigned))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--list", action="store_true")
    ap.add_argument("--stats", action="store_true")
    ap.add_argument("--build", action="store_true")
    ap.add_argument("--csv", default="")
    ap.add_argument("--track", default="", help="filter --list to a track file prefix, e.g. 05")
    ap.add_argument("--width", type=int, default=110)
    a = ap.parse_args()
    rows = load_all()
    ids = Counter(r["id"] for r in rows)
    dup_ids = [k for k, v in ids.items() if v > 1]
    if dup_ids:
        print("WARNING duplicate IDs across files:", dup_ids)
    if a.stats:
        c = Counter((r["track"], r["strength"].split()[0] if r["strength"] else "?") for r in rows)
        for t in sorted({r["track"] for r in rows}):
            print(t, {k[1]: v for k, v in c.items() if k[0] == t}, "total", sum(v for k, v in c.items() if k[0] == t))
        print("TOTAL", len(rows))
    if a.list:
        for r in rows:
            if a.track and not r["track"].startswith(a.track):
                continue
            st = (r["strength"] or "?")[0].upper()
            print(f"{r['id']} {st} | {r['who'][:45]} | {r['pain'][:a.width]}")
    if a.csv:
        with open(a.csv, "w", newline="", encoding="utf-8") as f:
            w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
            w.writeheader()
            w.writerows(rows)
    if a.build:
        build(rows)


if __name__ == "__main__":
    sys.exit(main())
